function deriveMetrics(cases: HealthCase[]): HealthMetrics {
  const byStatus = {
    borrador: 0,
    orientacion_iniciada: 0,
    seguimiento: 0,
    listo_consulta: 0,
    cerrado: 0,
    archivado: 0,
  };
  const byLanguage = { es: 0, nah: 0, maya: 0, zapoteco: 0 };

  cases.forEach((item) => {
    byStatus[item.status] += 1;
    byLanguage[item.language] += 1;
  });

  return {
    activeCases: cases.filter((item) => item.status !== "cerrado" && item.status !== "archivado").length,
    orientations: cases.reduce((total, item) => total + item.guidance.length, 0),
    pendingFollowups: cases.filter((item) => item.status === "seguimiento" || item.status === "listo_consulta").length,
    documents: cases.reduce((total, item) => total + item.documents.length, 0),
    alerts: cases.filter((item) => item.attentionLevel === "consulta_prioritaria" || item.attentionLevel === "posible_emergencia").length,
    closedCases: byStatus.cerrado,
    telehealthAppointments: mockAppointments.length,
    supplyAlerts: mockSupplyItems.filter((item) => item.availability === "desabasto_reportado" || item.availability === "disponibilidad_limitada").length,
    policiesInEvaluation: mockPolicyEvaluations.filter((item) => item.status !== "concluida").length,
    publicCommitments: mockPublicCommitments.length,
    solidarityRequests: mockSolidarityInitiatives.length,
    activeCommittees: 3,
    byStatus,
    byLanguage,
    preventiveTopics: [
      { label: "Hidratacion y observacion", value: 18 },
      { label: "Preparacion de consulta", value: 12 },
      { label: "Signos de alarma", value: 9 },
      { label: "Accesibilidad e idioma", value: 7 },
    ],
  };
}

